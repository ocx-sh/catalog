#!/usr/bin/env node
/**
 * Generates `docs/reference/theme-tokens.md` from `src/theme/styles/tokens/*.css`.
 *
 * The token reference is generated, never hand-written: a hand-maintained table
 * is precisely the thing that goes stale, and a stale API table is worse than
 * no table — it documents a contract the code no longer honours. This repo has
 * already shipped three false claims of that kind in one docs page.
 *
 * Lives in `scripts/`, not `src/`, for the same reason `pack-smoke.mjs` does:
 * it is maintainer tooling that never ships to a consumer (`scripts/` is not in
 * package.json's `files`). `renderTokenReference` is exported as a pure
 * string-in/string-out function so `test/build/token_docs_drift.test.ts` can
 * re-render from the real token files and byte-compare against the committed
 * page — that test is what proves this script correct, not branch coverage of
 * its filesystem glue.
 *
 * Run it after touching any token file:
 *   node scripts/gen-token-docs.mjs
 */
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { join, dirname } from "node:path";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
const TOKEN_FILES = ["palette.css", "type.css", "shape.css"];
export const OUTPUT = "docs/reference/theme-tokens.md";

/** The `:root { … }` / `.dark { … }` body of a token file, by brace depth. */
function block(css, selector) {
  const start = css.indexOf(`${selector} {`);
  if (start === -1) return "";
  let depth = 0;
  for (let i = css.indexOf("{", start); i < css.length; i++) {
    if (css[i] === "{") depth++;
    else if (css[i] === "}") {
      depth--;
      if (depth === 0) return css.slice(start, i);
    }
  }
  throw new Error(`unbalanced ${selector} block`);
}

function declarations(body) {
  const out = new Map();
  for (const m of body.matchAll(/^\s*(--ocx-[a-z0-9-]+)\s*:\s*([^;]+);/gm)) {
    out.set(m[1], m[2].trim());
  }
  return out;
}

/** Groups, in the order they are presented. A token matching no prefix lands in
 *  "Other" rather than being silently dropped — a missing row is how a token
 *  quietly stops being documented. */
const GROUPS = [
  ["Surfaces and borders", (n) => /^--ocx-color-(bg|surface|border|overlay)/.test(n)],
  ["Foreground", (n) => /^--ocx-color-fg/.test(n)],
  ["Accent", (n) => /^--ocx-color-accent/.test(n)],
  ["Status", (n) => /^--ocx-color-(success|warning|keyword)/.test(n)],
  ["Code", (n) => /^--ocx-color-code-/.test(n)],
  ["Monogram", (n) => /^--ocx-color-monogram-/.test(n)],
  ["Type", (n) => /^--ocx-(font|text)-/.test(n)],
  ["Shape and space", (n) => /^--ocx-(radius|space|border-width|shadow|header)-?/.test(n)],
  ["Motion", (n) => /^--ocx-duration-/.test(n)],
  ["Stacking", (n) => /^--ocx-z-/.test(n)],
];

export function renderTokenReference(sources) {
  const light = new Map();
  const dark = new Map();
  for (const name of TOKEN_FILES) {
    const css = sources[name] ?? "";
    for (const [k, v] of declarations(block(css, ":root"))) light.set(k, v);
    for (const [k, v] of declarations(block(css, ".dark"))) dark.set(k, v);
  }

  const isAlias = (v) => /^var\(--ocx-[a-z0-9-]+\)$/.test(v);
  const assigned = new Set();
  const lines = [];

  lines.push("# Theme tokens");
  lines.push("");
  lines.push("<!-- Generated by scripts/gen-token-docs.mjs. Do not edit by hand:");
  lines.push("     test/build/token_docs_drift.test.ts fails if this file and the");
  lines.push("     token sources disagree. Re-run the script instead. -->");
  lines.push("");
  lines.push(
    "Every value the theme renders comes from one of these CSS custom properties. " +
      "They are the public styling API: set any of them from the stylesheet you point " +
      "[`css`](config-schema.md) at, and the whole site follows.",
  );
  lines.push("");
  lines.push("## Overriding");
  lines.push("");
  lines.push(
    "Your stylesheet loads after the theme's, and the theme's own CSS is wrapped in " +
      "a `@layer ocx` cascade layer. Any rule you write is unlayered, and an unlayered " +
      "rule beats a layered one **at any specificity** — so you never need `!important` " +
      "and never need to out-specify an internal selector.",
  );
  lines.push("");
  lines.push("```css");
  lines.push(":root {");
  lines.push("  --ocx-color-accent: #2563eb;");
  lines.push("  --ocx-radius-lg: 0; /* square corners everywhere */");
  lines.push("}");
  lines.push("");
  lines.push(".dark {");
  lines.push("  --ocx-color-accent: #60a5fa;");
  lines.push("}");
  lines.push("```");
  lines.push("");
  lines.push(
    "**Set both blocks.** `:root` and `.dark` have the same specificity and both match " +
      "`<html>`, so a `:root`-only override wins in dark mode too and pins that token to " +
      "its light value. Overriding only `:root` is the single most common way to " +
      "accidentally break dark mode.",
  );
  lines.push("");
  lines.push(
    "A token whose default is shown as `var(--ocx-…)` is an **alias**: it follows " +
      "whatever that token resolves to, in both colour schemes, so it needs no `.dark` " +
      "entry of its own.",
  );
  lines.push("");

  for (const [title, match] of GROUPS) {
    const names = [...light.keys()].filter((n) => !assigned.has(n) && match(n));
    if (names.length === 0) continue;
    names.forEach((n) => assigned.add(n));
    const anyDark = names.some((n) => dark.has(n));
    lines.push(`## ${title}`);
    lines.push("");
    lines.push(anyDark ? "| Token | Light | Dark |" : "| Token | Value |");
    lines.push(anyDark ? "|---|---|---|" : "|---|---|");
    for (const n of names) {
      const l = light.get(n);
      const cell = isAlias(l) ? `\`${l}\` (alias)` : `\`${l}\``;
      lines.push(anyDark ? `| \`${n}\` | ${cell} | \`${dark.get(n) ?? "—"}\` |` : `| \`${n}\` | ${cell} |`);
    }
    lines.push("");
  }

  const leftover = [...light.keys()].filter((n) => !assigned.has(n));
  if (leftover.length > 0) {
    lines.push("## Other");
    lines.push("");
    lines.push("| Token | Light | Dark |");
    lines.push("|---|---|---|");
    for (const n of leftover) lines.push(`| \`${n}\` | \`${light.get(n)}\` | \`${dark.get(n) ?? "—"}\` |`);
    lines.push("");
  }

  return lines.join("\n");
}

export function readTokenSources(root = ROOT) {
  return Object.fromEntries(
    TOKEN_FILES.map((f) => [f, readFileSync(join(root, "src/theme/styles/tokens", f), "utf8")]),
  );
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const out = renderTokenReference(readTokenSources());
  writeFileSync(join(ROOT, OUTPUT), out.endsWith("\n") ? out : `${out}\n`, "utf8");
  console.log(`wrote ${OUTPUT}`);
}
